const SEQ = {
  idle: [0, 0, 1, 1, 0, 0, 1, 1, 2, 0],
  guard: [0, 0, 0, 1, 1],
  book: [0, 0, 0, 1, 0, 0, 2, 0],
};

const RGB = {};
for (const [c, hex] of Object.entries(PAL)) {
  const n = parseInt(hex.slice(1), 16);
  RGB[c] = [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

const cache = new Map();

/** How many frames an action has (an unknown one is idle). */
export function chibiFrameCount(action) {
  return (FRAMES[action] || FRAMES.idle).length;
}

/** Which frame is showing at time t (seconds). */
function frameAt(action, t) {
  const seq = SEQ[action];
  const len = seq ? seq.length : FRAMES[action].length;
  let i = Math.floor((Number.isFinite(t) ? t : 0) * CHIBI_FPS) % len;
  if (i < 0) i += len;
  return seq ? seq[i] : i;
}

/** One frame as a canvas, `s` whole pixels per art pixel. Cached. */
function bake(action, f, s, gray) {
  const key = `${action}|${f}|${s}|${gray ? 1 : 0}`;
  let cv = cache.get(key);
  if (cv) return cv;
  const rows = FRAMES[action][f];
  cv = document.createElement('canvas');
  cv.width = CHIBI_W * s;
  cv.height = CHIBI_H * s;
  const g = cv.getContext('2d');
  g.imageSmoothingEnabled = false;
  const img = g.createImageData(cv.width, cv.height);
  const d = img.data;
  for (let y = 0; y < CHIBI_H; y++) {
    const row = rows[y];
    for (let x = 0; x < CHIBI_W; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      let [r, gg, b] = RGB[ch];
      if (gray) {
        // a disabled control: the same drawing, desaturated and dimmed
        const l = r * 0.3 + gg * 0.55 + b * 0.15;
        r = gg = b = l * 0.62 + 18;
      }
      for (let yy = 0; yy < s; yy++) {
        let o = ((y * s + yy) * cv.width + x * s) * 4;
        for (let xx = 0; xx < s; xx++, o += 4) {
          d[o] = r; d[o + 1] = gg; d[o + 2] = b; d[o + 3] = 255;
        }
      }
    }
  }
  g.putImageData(img, 0, 0);
  cache.set(key, cv);
  return cv;
}

/**
 * Draw the frame of `action` showing at time `t` (seconds), centred on
 * (cx, cy), `scale` whole pixels per art pixel. opts.gray draws it
 * desaturated (a disabled button), opts.alpha fades it, and opts.frame holds
 * one frame instead of following the clock.
 */
export function drawChibi(ctx, action, cx, cy, t = 0, scale = 1, opts = {}) {
  const name = FRAMES[action] ? action : 'idle';
  const s = Math.max(1, Math.round(scale) || 1);
  const n = FRAMES[name].length;
  const f = Number.isInteger(opts.frame) ? ((opts.frame % n) + n) % n : frameAt(name, t);
  const cv = bake(name, f, s, !!opts.gray);
  const x = Math.round(cx - cv.width / 2), y = Math.round(cy - cv.height / 2);
  const a = opts.alpha;
  if (a !== undefined && a !== 1) {
    const prev = ctx.globalAlpha;
    ctx.globalAlpha = prev * a;
    ctx.drawImage(cv, x, y);
    ctx.globalAlpha = prev;
  } else {
    ctx.drawImage(cv, x, y);
  }
  return true;
}

