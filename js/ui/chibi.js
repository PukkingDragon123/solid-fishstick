// CRABDEN - the chibi crab.
//
// A little version of you for the buttons: the old desert crab drawn small
// and round, a seedling on the crown of its shell, moss down one side and a
// barnacle on the shoulder, two bead eyes with a glint in each - doing the
// thing the button does. It digs with a spade, swings a pickaxe at a rock,
// chops a stump, turns the brass valve, holds up what it found.
//
// Every frame is hand-placed: 20 rows of 24 characters, one character a
// pixel, '.' clear, every other character a colour in PAL. Light comes from
// the top left, there is a dark line round everything, and each frame is
// baked once per scale into a canvas. The animation runs at five frames a
// second and loops; an action with a SEQ entry plays its frames in that order
// (so idle can breathe for a while and blink once).
//
//   drawChibi(ctx, 'dig', x, y, t, 2)          the spade, 2 px a pixel
//   drawChibi(ctx, 'mine', x, y, t, 1, { gray: true })   disabled
//
// An action that is not here draws 'idle'.

